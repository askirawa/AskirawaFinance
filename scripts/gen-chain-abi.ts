/**
 * Regenerates src/chain/abi.ts from the Foundry artifacts so the frontend ABI can never drift from the contracts.
 * Run after `forge build`:  bun run scripts/gen-chain-abi.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'

type AbiItem = { type: string; name?: string; stateMutability?: string; inputs?: unknown[]; outputs?: unknown[] }

function load(name: string): AbiItem[] {
  const path = `contracts/out/${name}.sol/${name}.json`
  const artifact = JSON.parse(readFileSync(path, 'utf8')) as { abi: AbiItem[] }
  return artifact.abi
}

/** internalType only bloats the bundle; viem does not need it. */
function strip(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(strip)
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .filter(([k]) => k !== 'internalType')
        .map(([k, v]) => [k, strip(v)]),
    )
  }
  return value
}

function emit(constName: string, abi: AbiItem[]): string {
  const lines = abi.map((item) => '  ' + JSON.stringify(strip(item)) + ',')
  return `export const ${constName} = [\n${lines.join('\n')}\n] as const\n`
}

const treasury = load('AskirawaTreasury')
const module_ = load('RecurringPaymentModule')
const recovery = load('TreasuryRecovery').filter(
  (i) => i.type === 'event' || (i.type === 'function' && (i.stateMutability === 'view' || i.stateMutability === 'pure')),
)

const out = `// GENERATED by scripts/gen-chain-abi.ts from contracts/out. Do not edit by hand.
// Treasury v2 contracts. Unaudited.

${emit('treasuryAbi', treasury)}
${emit('recurringModuleAbi', module_)}
${emit('recoveryAbi', recovery)}`

writeFileSync('src/chain/abi.ts', out)
console.log('wrote src/chain/abi.ts', { treasury: treasury.length, module: module_.length, recovery: recovery.length })
